/// Concrete filesystem-backed store carrying its resolved root (§5.1).
///
/// The injected root keeps tests pointed at a temp dir while production
/// constructs it via `portable::app_data_dir(app)?` ([`LocalAssetStore::for_app`]),
/// so portable installs (`Data/` next to the exe) and normal installs share
/// exactly one path-resolution code path (contract §2.1, plan §4).
pub struct LocalAssetStore {
    root: PathBuf,
}

impl LocalAssetStore {
    /// Test/headless constructor: caller supplies the portable-resolved root.
    ///
    /// Does not touch the filesystem; use [`LocalAssetStore::create_at`] when
    /// the root may not exist yet.
    pub fn with_root(root: PathBuf) -> Self {
        Self { root }
    }

    /// Constructor that creates the store root if it is missing.
    pub fn create_at(root: PathBuf) -> Result<Self, AssetStoreError> {
        fs::create_dir_all(&root).map_err(|e| AssetStoreError::Io {
            key: root_pseudo_key(),
            detail: format!("cannot create store root {}: {e}", root.display()),
        })?;
        Ok(Self { root })
    }

    /// Production constructor (contract §2.1 rule 2): the portable decision is
    /// applied once here, never again per key. Never calls
    /// `app.path().app_data_dir()` directly.
    pub fn for_app(app: &tauri::AppHandle) -> Result<Self, AssetStoreError> {
        let root = crate::portable::app_data_dir(app).map_err(|e| AssetStoreError::Io {
            key: root_pseudo_key(),
            detail: format!("cannot resolve portable app data dir: {e}"),
        })?;
        Self::create_at(root)
    }

    pub fn root(&self) -> &Path {
        &self.root
    }

    /// Defence in depth on top of [`StorageKey::parse`]: the resolved path must
    /// stay inside the root and must not contain a `..` component after the
    /// join, even if the grammar check were ever weakened.
    fn contained(&self, path: &Path, key: &StorageKey) -> Result<(), AssetStoreError> {
        if path.components().any(|c| matches!(c, Component::ParentDir)) {
            return Err(AssetStoreError::UntrustedPathRejected {
                key: key.clone(),
                detail: "resolved path contains a `..` component".to_string(),
            });
        }
        if !path.starts_with(&self.root) {
            return Err(AssetStoreError::UntrustedPathRejected {
                key: key.clone(),
                detail: format!(
                    "resolved path escapes the store root {}",
                    self.root.display()
                ),
            });
        }
        Ok(())
    }

    /// Rejects symlinks / Windows reparse points anywhere between the root and
    /// the target (plan §12: symlinks are refused before commit). Components
    /// that do not exist yet are simply skipped.
    fn ensure_no_reparse_point(
        &self,
        path: &Path,
        key: &StorageKey,
    ) -> Result<(), AssetStoreError> {
        let relative = match path.strip_prefix(&self.root) {
            Ok(rel) => rel,
            Err(_) => {
                return Err(AssetStoreError::UntrustedPathRejected {
                    key: key.clone(),
                    detail: "path is not inside the store root".to_string(),
                })
            }
        };
        let mut probe = self.root.clone();
        for component in relative.components() {
            probe.push(component);
            match fs::symlink_metadata(&probe) {
                Ok(meta) if meta.file_type().is_symlink() => {
                    return Err(AssetStoreError::UntrustedPathRejected {
                        key: key.clone(),
                        detail: format!("symlink/reparse point at {}", probe.display()),
                    })
                }
                Ok(_) => {}
                // Not created yet — nothing to distrust.
                Err(_) => break,
            }
        }
        Ok(())
    }

    /// Resolve + both defence-in-depth checks, used by every I/O entry point.
    fn checked_path(&self, key: &StorageKey) -> Result<PathBuf, AssetStoreError> {
        let path = self.resolve(key)?;
        self.ensure_no_reparse_point(&path, key)?;
        Ok(path)
    }
}

/// Placeholder key for errors that concern the root itself rather than a key.
fn root_pseudo_key() -> StorageKey {
    StorageKey("<store-root>".to_string())
}

fn io_error(key: &StorageKey, detail: impl fmt::Display) -> AssetStoreError {
    AssetStoreError::Io {
        key: key.clone(),
        detail: detail.to_string(),
    }
}

/// Unique staging name in the *same* directory as the final key, so the rename
/// in step 4 stays on one volume and is therefore atomic (contract §5.2).
///
/// Deviation from the contract's literal `<key>.part` spelling, deliberate: a
/// bare `<key>.part` for `000004-microphone.wav` would collide with the
/// recorder's live `.part` chunk (which is itself a valid grammar key) and with
/// a concurrent put of the same key. The uniqueness token makes the staging
/// name un-parseable as a `StorageKey`, so the §7 startup scan classifies a
/// crashed staging file as an orphan temp instead of adopting it as audio. The
/// `.part` suffix is kept as the crash marker the contract relies on.
fn staging_path_for(final_path: &Path) -> PathBuf {
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let ticket = COUNTER.fetch_add(1, Ordering::Relaxed);
    let name = final_path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_else(|| "asset".to_string());
    let staged = format!("{name}.{}-{ticket}.staging.part", std::process::id());
    match final_path.parent() {
        Some(parent) => parent.join(staged),
        None => PathBuf::from(staged),
    }
}

fn to_hex(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        out.push_str(&format!("{b:02x}"));
    }
    out
}

fn finish_hash(hasher: Sha256, key: &StorageKey) -> Result<ContentHash, AssetStoreError> {
    ContentHash::from_digest_hex(&to_hex(&hasher.finalize()))
        .map_err(|e| io_error(key, format!("digest encoding failed: {e}")))
}

/// Streams `reader` into `writer`, hashing on the way (V1: free, computed while
/// writing). Returns the byte count.
fn copy_hashing<R: Read, W: Write>(
    mut reader: R,
    writer: &mut W,
    hasher: &mut Sha256,
) -> io::Result<u64> {
    let mut buffer = vec![0u8; 64 * 1024];
    let mut total: u64 = 0;
    loop {
        let read = reader.read(&mut buffer)?;
        if read == 0 {
            return Ok(total);
        }
        hasher.update(&buffer[..read]);
        writer.write_all(&buffer[..read])?;
        total = total.saturating_add(read as u64);
    }
}

/// fsync of a *directory* handle (contract §5.2 step 5).
///
/// Windows: a no-op by necessity, not by laziness. `FlushFileBuffers` — what
/// `File::sync_all` calls — requires write access to the handle, and Windows
/// grants no write access to a directory handle, so the call always returns
/// `ERROR_ACCESS_DENIED` (os error 5) even when the directory opens fine with
/// `FILE_FLAG_BACKUP_SEMANTICS`. There is no supported user-mode API to flush a
/// directory entry on NTFS; durability of the step-4 rename is provided by
/// NTFS's own metadata journal, which is exactly what the contract's
/// "`std::fs::rename` on NTFS is atomic for the directory-entry swap" note
/// relies on. On Unix the fsync is real and is performed.
fn fsync_dir(dir: &Path) -> io::Result<()> {
    #[cfg(windows)]
    {
        // Still assert the directory exists and is reachable, so a genuinely
        // broken parent surfaces here rather than at the next write.
        let meta = fs::metadata(dir)?;
        if !meta.is_dir() {
            return Err(io::Error::new(
                io::ErrorKind::NotADirectory,
                format!("{} is not a directory", dir.display()),
            ));
        }
        Ok(())
    }
    #[cfg(not(windows))]
    {
        fs::File::open(dir)?.sync_all()
    }
}

/// Hashes an existing file end to end (V2). `Ok(None)` = file is missing.
fn hash_file(path: &Path, key: &StorageKey) -> Result<Option<(ContentHash, u64)>, AssetStoreError> {
    let file = match fs::File::open(path) {
        Ok(f) => f,
        Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(io_error(key, e)),
    };
    let mut hasher = Sha256::new();
    let mut sink = io::sink();
    let size = copy_hashing(file, &mut sink, &mut hasher).map_err(|e| io_error(key, e))?;
    Ok(Some((finish_hash(hasher, key)?, size)))
}

impl fmt::Debug for LocalAssetStore {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "LocalAssetStore({})", self.root.display())
    }
}

/// Persistence seam for durable, content-addressed blob storage (§5.1).
///
/// The only function in the codebase allowed to turn a storage key into an
/// absolute path is [`AssetStore::resolve`] (§2.1 rule 2, single resolution
/// point). In Tauri contexts it is `portable::resolve_app_data(self.app,
/// key.as_str())`; headless contexts join onto `portable::data_dir()`.
pub trait AssetStore: Send + Sync {
    /// Resolve a key to its absolute path. The single resolution point (§2.1).
    fn resolve(&self, key: &StorageKey) -> Result<PathBuf, AssetStoreError>;

    /// Atomic write-commit (§5.2). Creates parent directories as needed.
    fn put(&self, req: PutRequest) -> Result<PutResult, AssetStoreError>;

    /// Open a bounded reader. `ReadVerification::Full` hashes while reading
    /// and returns `AssetStoreError::HashMismatch` on first read error.
    fn get(
        &self,
        key: &StorageKey,
        verification: ReadVerification,
    ) -> Result<Box<dyn std::io::Read + Send>, AssetStoreError>;

    fn exists(&self, key: &StorageKey) -> Result<bool, AssetStoreError>;
    fn size(&self, key: &StorageKey) -> Result<u64, AssetStoreError>;

    /// V2 verification: full read + hash compare.
    fn verify(
        &self,
        key: &StorageKey,
        expected: &ContentHash,
    ) -> Result<VerifyReport, AssetStoreError>;

    /// Unlink a single key. Content-first deletion: the caller commits the
    /// DB/manifest state change *after* this returns Ok (§9.2).
    fn delete(&self, key: &StorageKey) -> Result<(), AssetStoreError>;

    /// Remove an entire session directory tree (delete level 3 only, §9).
    /// Refuses keys that are not `meetings/<id>` roots.
    fn delete_meeting_tree(&self, meeting_id: &str) -> Result<DeleteReport, AssetStoreError>;
}

impl AssetStore for LocalAssetStore {
    /// The single resolution point (§2.1 rule 2). Every absolute path in the
    /// process is derived here and nowhere else.
    fn resolve(&self, key: &StorageKey) -> Result<PathBuf, AssetStoreError> {
        // Re-validate: a `StorageKey` can only exist via `parse`, but resolve is
        // the security choke point, so it does not take that on trust.
        let validated = StorageKey::parse(key.as_str())?;
        let mut path = self.root.clone();
        for component in validated.as_str().split('/') {
            path.push(component);
        }
        self.contained(&path, key)?;
        Ok(path)
    }

    /// Atomic write-commit, contract §5.2 steps 1–6. A crash at any point
    /// leaves either the previous content or the new content at the final key,
    /// never a partial file: the rename is the only commit point.
    fn put(&self, req: PutRequest) -> Result<PutResult, AssetStoreError> {
        let PutRequest {
            key,
            kind: _,
            expected_hash,
            content,
        } = req;

        // 1. resolve (rejects invalid keys before any filesystem call)
        let final_path = self.resolve(&key)?;
        let parent = final_path
            .parent()
            .ok_or_else(|| io_error(&key, "resolved path has no parent directory"))?
            .to_path_buf();
        fs::create_dir_all(&parent)
            .map_err(|e| io_error(&key, format!("cannot create {}: {e}", parent.display())))?;
        self.ensure_no_reparse_point(&final_path, &key)?;

        // 2. stage — same directory ⇒ same volume ⇒ atomic rename
        let staging = staging_path_for(&final_path);
        let mut hasher = Sha256::new();
        let staged_file = fs::File::create(&staging)
            .map_err(|e| io_error(&key, format!("cannot create {}: {e}", staging.display())))?;
        let mut writer = io::BufWriter::new(staged_file);
        let size_bytes = match content {
            PutSource::File(source) => {
                let source_file = fs::File::open(&source).map_err(|e| {
                    io_error(
                        &key,
                        format!("cannot read source {}: {e}", source.display()),
                    )
                })?;
                copy_hashing(source_file, &mut writer, &mut hasher)
            }
            PutSource::Reader(reader) => copy_hashing(reader, &mut writer, &mut hasher),
        }
        .map_err(|e| io_error(&key, e))?;

        // 3. seal — flush + fsync, then compare against the expected hash
        let staged_file = writer
            .into_inner()
            .map_err(|e| io_error(&key, format!("flush of staging file failed: {e}")))?;
        staged_file
            .sync_all()
            .map_err(|e| AssetStoreError::CommitFailed {
                key: key.clone(),
                temp_path: staging.display().to_string(),
                detail: format!("fsync of staging file failed: {e}"),
            })?;
        drop(staged_file);

        let hash = finish_hash(hasher, &key)?;
        if let Some(expected) = expected_hash {
            if expected != hash {
                // Staging file is deliberately left in place: forensics beats
                // tidiness for audio (contract §5.2).
                return Err(AssetStoreError::HashMismatch {
                    key,
                    expected,
                    actual: Some(hash),
                });
            }
        }

        // 4. commit — atomic rename (overwrites an existing key on NTFS too)
        fs::rename(&staging, &final_path).map_err(|e| AssetStoreError::CommitFailed {
            key: key.clone(),
            temp_path: staging.display().to_string(),
            detail: format!("rename into place failed: {e}"),
        })?;

        // 5. durabilize — fsync the parent directory entry
        fsync_dir(&parent).map_err(|e| AssetStoreError::CommitFailed {
            key: key.clone(),
            temp_path: staging.display().to_string(),
            detail: format!("fsync of {} failed: {e}", parent.display()),
        })?;

        // 6. report — the CALLER now commits the DB row / manifest entry
        Ok(PutResult {
            key,
            hash,
            size_bytes,
        })
    }

    /// `ReadVerification::Full` does a streaming pre-pass that reads the whole
    /// file, so an unreadable or truncated asset fails here rather than halfway
    /// through the caller's consumption. `get` takes no expected hash, so the
    /// actual comparison lives in [`AssetStore::verify`] (V2/V4).
    fn get(
        &self,
        key: &StorageKey,
        verification: ReadVerification,
    ) -> Result<Box<dyn Read + Send>, AssetStoreError> {
        let path = self.checked_path(key)?;
        if verification == ReadVerification::Full && hash_file(&path, key)?.is_none() {
            return Err(AssetStoreError::NotFound { key: key.clone() });
        }
        let file = match fs::File::open(&path) {
            Ok(f) => f,
            Err(e) if e.kind() == io::ErrorKind::NotFound => {
                return Err(AssetStoreError::NotFound { key: key.clone() })
            }
            Err(e) => return Err(io_error(key, e)),
        };
        Ok(Box::new(io::BufReader::new(file)))
    }

    fn exists(&self, key: &StorageKey) -> Result<bool, AssetStoreError> {
        let path = self.checked_path(key)?;
        match fs::metadata(&path) {
            Ok(meta) => Ok(meta.is_file()),
            Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(false),
            Err(e) => Err(io_error(key, e)),
        }
    }

    fn size(&self, key: &StorageKey) -> Result<u64, AssetStoreError> {
        let path = self.checked_path(key)?;
        match fs::metadata(&path) {
            Ok(meta) => Ok(meta.len()),
            Err(e) if e.kind() == io::ErrorKind::NotFound => {
                Err(AssetStoreError::NotFound { key: key.clone() })
            }
            Err(e) => Err(io_error(key, e)),
        }
    }

    /// V2 verification. A missing file or a digest mismatch is *reported*
    /// (`ok == false`), not raised: §3.2 requires the caller to mark the row
    /// `damaged`/`corrupted`, and it never re-downloads or deletes silently.
    /// `Err` is reserved for invalid keys and genuine I/O faults.
    fn verify(
        &self,
        key: &StorageKey,
        expected: &ContentHash,
    ) -> Result<VerifyReport, AssetStoreError> {
        let path = self.checked_path(key)?;
        match hash_file(&path, key)? {
            None => Ok(VerifyReport {
                key: key.clone(),
                expected: expected.clone(),
                actual: None,
                size_bytes: None,
                ok: false,
            }),
            Some((actual, size_bytes)) => Ok(VerifyReport {
                key: key.clone(),
                expected: expected.clone(),
                ok: &actual == expected,
                actual: Some(actual),
                size_bytes: Some(size_bytes),
            }),
        }
    }

    /// Content-first deletion (§9.2 rule 1). Idempotent: an already absent file
    /// is `Ok(())`, mirroring `DeleteReport::already_missing` ("row said
    /// present, file gone" is harmless, never an error).
    fn delete(&self, key: &StorageKey) -> Result<(), AssetStoreError> {
        let path = self.checked_path(key)?;
        match fs::remove_file(&path) {
            Ok(()) => {}
            Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(()),
            Err(e) => return Err(io_error(key, e)),
        }
        if let Some(parent) = path.parent() {
            // Durability of the unlink; a failure here does not resurrect the
            // file, so it is reported as I/O rather than swallowed.
            fsync_dir(parent).map_err(|e| io_error(key, format!("fsync after unlink: {e}")))?;
        }
        Ok(())
    }

    /// Delete level 3 (§9.1): the whole `meetings/<id>/` subtree, nothing else.
    /// Refuses anything that is not a `meetings/<uuid>` root and anything that
    /// would resolve outside the store root.
    fn delete_meeting_tree(&self, meeting_id: &str) -> Result<DeleteReport, AssetStoreError> {
        // Reuses the grammar's UUID rule: a non-UUID meeting id cannot name a
        // directory, so `..`, `C:\…` and friends never reach the filesystem.
        let anchor = StorageKey::meeting_manifest(meeting_id)?;
        let tree = self
            .resolve(&anchor)?
            .parent()
            .ok_or_else(|| io_error(&anchor, "meeting tree has no parent"))?
            .to_path_buf();
        self.contained(&tree, &anchor)?;
        if tree == self.root {
            return Err(AssetStoreError::UntrustedPathRejected {
                key: anchor,
                detail: "refusing to delete the store root".to_string(),
            });
        }
        self.ensure_no_reparse_point(&tree, &anchor)?;

        let mut report = DeleteReport {
            removed_keys: Vec::new(),
            removed_bytes: 0,
            already_missing: Vec::new(),
        };
        match fs::symlink_metadata(&tree) {
            Ok(meta) if meta.is_dir() => {}
            Ok(_) => {
                return Err(AssetStoreError::UntrustedPathRejected {
                    key: anchor,
                    detail: format!("{} is not a directory", tree.display()),
                })
            }
            Err(e) if e.kind() == io::ErrorKind::NotFound => {
                report.already_missing.push(anchor);
                return Ok(report);
            }
            Err(e) => return Err(io_error(&anchor, e)),
        }

        collect_tree(&tree, &tree, meeting_id, &anchor, &mut report)?;
        fs::remove_dir_all(&tree)
            .map_err(|e| io_error(&anchor, format!("remove {}: {e}", tree.display())))?;
        if let Some(parent) = tree.parent() {
            fsync_dir(parent)
                .map_err(|e| io_error(&anchor, format!("fsync after tree delete: {e}")))?;
        }
        Ok(report)
    }
}

/// Inventory of what the level-3 delete is about to remove, so the UI can
/// render the `DeleteReport` verbatim (§9.2 rule 5). Symlinked entries are
/// counted but never followed.
fn collect_tree(
    tree_root: &Path,
    dir: &Path,
    meeting_id: &str,
    anchor: &StorageKey,
    report: &mut DeleteReport,
) -> Result<(), AssetStoreError> {
    let entries = fs::read_dir(dir)
        .map_err(|e| io_error(anchor, format!("read_dir {}: {e}", dir.display())))?;
    for entry in entries {
        let entry = entry.map_err(|e| io_error(anchor, format!("dir entry: {e}")))?;
        let path = entry.path();
        let meta = fs::symlink_metadata(&path)
            .map_err(|e| io_error(anchor, format!("stat {}: {e}", path.display())))?;
        if meta.file_type().is_symlink() {
            continue;
        }
        if meta.is_dir() {
            collect_tree(tree_root, &path, meeting_id, anchor, report)?;
            continue;
        }
        report.removed_bytes = report.removed_bytes.saturating_add(meta.len());
        if let Ok(relative) = path.strip_prefix(tree_root) {
            let joined: Vec<String> = relative
                .components()
                .filter_map(|c| match c {
                    Component::Normal(part) => Some(part.to_string_lossy().into_owned()),
                    _ => None,
                })
                .collect();
            // Staging/orphan temp files are counted in the byte total but have
            // no valid key, so they are simply not listed.
            if let Ok(key) =
                StorageKey::parse(&format!("meetings/{meeting_id}/{}", joined.join("/")))
            {
                report.removed_keys.push(key);
            }
        }
    }
    Ok(())
}

