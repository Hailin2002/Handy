    #[test]
    fn verify_detects_on_disk_corruption() {
        let (_guard, store) = store();
        let key = chunk(MID, 6);
        let payload = b"original content".to_vec();
        let expected = put_bytes(&store, &key, &payload).hash;
        assert!(store.verify(&key, &expected).expect("verify clean").ok);

        // Mutate the committed file behind the back of the store.
        let path = store.resolve(&key).expect("resolve");
        fs::write(&path, b"tampered content").expect("tamper");

        let report = store.verify(&key, &expected).expect("verify tampered");
        assert!(!report.ok, "corruption must be detected");
        assert_eq!(report.expected, expected);
        assert_eq!(report.actual, Some(sha256_of(b"tampered content")));
        assert_eq!(report.size_bytes, Some(16));

        // Truncation is caught too.
        fs::write(&path, b"").expect("truncate");
        assert!(!store.verify(&key, &expected).expect("verify empty").ok);
    }

