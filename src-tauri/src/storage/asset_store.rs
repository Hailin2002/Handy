/// Single hash algorithm for v1 (contract §3.2). The string is persisted so a
/// later algorithm change is a migration, not a silent change.
pub const HASH_ALGORITHM: &str = "sha256";

/// Maximum storage-key length in UTF-8 bytes (contract §2.2).
const MAX_KEY_BYTES: usize = 512;

/// Fixed source component of an audio chunk file name (contract §2.2).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AudioSource {
    Microphone,
    System,
}

impl AudioSource {
    /// The exact lower-case key component mandated by the §2.2 grammar.
    pub const fn as_component(self) -> &'static str {
        match self {
            AudioSource::Microphone => "microphone",
            AudioSource::System => "system",
        }
    }

    fn parse(component: &str) -> Option<Self> {
        match component {
            "microphone" => Some(AudioSource::Microphone),
            "system" => Some(AudioSource::System),
            _ => None,
        }
    }
}

/// Generic-kind discriminator for puts (contract §5.1).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AssetKind {
    /// Generic committed blob (import, export, media). Key: `assets/<id>/…`
    Blob,
    /// Meeting-audio chunk. Key: `meetings/<mid>/audio/<file>`
    MeetingAudio,
    /// Regenerable export artifact. Key: `meetings/<mid>/export/<file>`
    MeetingExport,
    /// Quarantined recovery file. Key: `meetings/<mid>/recovery/<file>`
    Recovery,
}

/// Stable asset identity: `asst_<uuid-v4>`, hyphenated lower-case (§3.1).
///
/// Not derived from file content and not derived from SQLite autoincrement;
/// generated by the caller (domain service) so a DB row and its files can be
/// committed in either order.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct AssetId(String);

impl AssetId {
    /// Validates the `asst_` + lower-case hyphenated UUID v4 shape.
    pub fn parse_prefixed(raw: &str) -> Result<Self, AssetStoreError> {
        let uuid = raw
            .strip_prefix("asst_")
            .ok_or_else(|| invalid(format!("asset id missing `asst_` prefix: {raw:?}")))?;
        if !is_lower_uuid(uuid) {
            return Err(invalid(format!(
                "asset id suffix is not a lower-case hyphenated UUID: {raw:?}"
            )));
        }
        Ok(AssetId(raw.to_string()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for AssetId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// Lower-case `sha256-<64 hex>` over the exact byte range on disk (§3.2).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ContentHash(String);

impl ContentHash {
    /// Builds from the bare 64-digit digest; case-insensitive on input,
    /// always stored lower-case ("hash encoding").
    pub fn from_digest_hex(digest_hex: &str) -> Result<Self, AssetStoreError> {
        if digest_hex.len() != 64 || !digest_hex.bytes().all(|b| b.is_ascii_hexdigit()) {
            return Err(invalid(format!(
                "{HASH_ALGORITHM} digest must be exactly 64 hex characters"
            )));
        }
        Ok(ContentHash(format!(
            "{HASH_ALGORITHM}-{}",
            digest_hex.to_ascii_lowercase()
        )))
    }

    /// Parses an already-encoded `sha256-<64 hex>` string.
    pub fn parse_encoded(encoded: &str) -> Result<Self, AssetStoreError> {
        let digest = encoded
            .strip_prefix(HASH_ALGORITHM)
            .and_then(|rest| rest.strip_prefix('-'))
            .ok_or_else(|| invalid(format!("content hash must start with `{HASH_ALGORITHM}-`")))?;
        Self::from_digest_hex(digest)
    }

    /// The full persisted encoding, e.g. `sha256-e3b0c4…`.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// The bare lower-case digest without the algorithm prefix.
    pub fn digest_hex(&self) -> &str {
        &self.0[HASH_ALGORITHM.len() + 1..]
    }
}

impl fmt::Display for ContentHash {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// Relative, forward-slash storage key validated against the §2.2 grammar.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct StorageKey(String);

impl StorageKey {
    /// Parses and validates against the §2.2 grammar. `Err` on any absolute,
    /// traversing or out-of-grammar key (contract-normative function).
    ///
    /// This is the choke point enforcing the plan-§12 untrusted-input rules
    /// and the §2.1 no-absolute-path rule: nothing outside the two grammars
    /// (`meetings/…`, `assets/…`) can ever become a key.
    pub fn parse(raw: &str) -> Result<StorageKey, AssetStoreError> {
        if raw.is_empty() {
            return Err(invalid("empty storage key"));
        }
        if raw.len() > MAX_KEY_BYTES {
            return Err(invalid(format!(
                "storage key exceeds {MAX_KEY_BYTES} bytes"
            )));
        }
        // Backslashes and NUL are rejected outright (Windows separators must
        // never smuggle an absolute or escaping path through).
        if raw.contains('\\') {
            return Err(invalid("backslash in storage key"));
        }
        if raw.contains('\0') {
            return Err(invalid("NUL byte in storage key"));
        }

        let components: Vec<&str> = raw.split('/').collect();
        // Rejects leading `/`, trailing `/` and empty `//` segments alike.
        if components.iter().any(|c| c.is_empty()) {
            return Err(invalid(
                "empty path component (leading/trailing/double slash)",
            ));
        }
        if components.iter().any(|c| *c == "." || *c == "..") {
            return Err(invalid("`.` or `..` path traversal component"));
        }
        for c in &components {
            if !is_key_component(c) {
                return Err(invalid(format!(
                    "component {c:?} outside `[A-Za-z0-9._-]+` (rejects drive letters, `:` etc.)"
                )));
            }
        }

        match components.as_slice() {
            ["meetings", meeting_id, "manifest.json"] => require_uuid(meeting_id)?,
            ["meetings", meeting_id, "audio", chunk_file] => {
                require_uuid(meeting_id)?;
                parse_chunk_file(chunk_file)?;
            }
            ["meetings", meeting_id, "export", export_file] => {
                require_uuid(meeting_id)?;
                parse_export_file(export_file)?;
            }
            ["meetings", meeting_id, "recovery", quarantined_name] => {
                require_uuid(meeting_id)?;
                // Store-generated quarantine name; generic component rules
                // already checked above.
                let _ = quarantined_name;
            }
            ["assets", asset_id, asset_file] => {
                require_uuid(asset_id)?;
                parse_asset_file(asset_file)?;
            }
            _ => {
                return Err(invalid(format!(
                    "key {raw:?} does not match the meetings/assets grammars"
                )));
            }
        }

        Ok(StorageKey(raw.to_string()))
    }

    // ---- deterministic derivation helpers (§2.2 productions) ------------

    /// `meetings/<meeting-id>/manifest.json`
    pub fn meeting_manifest(meeting_id: &str) -> Result<Self, AssetStoreError> {
        Self::parse(&format!("meetings/{meeting_id}/manifest.json"))
    }

    /// `meetings/<meeting-id>/audio/<seq>-<source>(.wav|.wav.part)`
    ///
    /// `sequence` must fit the 6-digit production (`000001`–`999999`);
    /// `part_open` selects the live `.wav.part` form.
    pub fn audio_chunk(
        meeting_id: &str,
        sequence: u32,
        source: AudioSource,
        part_open: bool,
    ) -> Result<Self, AssetStoreError> {
        if sequence > 999_999 {
            return Err(invalid(format!(
                "chunk sequence {sequence} exceeds the 6-digit production"
            )));
        }
        let suffix = if part_open { ".wav.part" } else { ".wav" };
        Self::parse(&format!(
            "meetings/{meeting_id}/audio/{sequence:06}-{}{suffix}",
            source.as_component()
        ))
    }

    /// `meetings/<meeting-id>/export/<store-generated-name>.<ext>`
    pub fn meeting_export(meeting_id: &str, export_file: &str) -> Result<Self, AssetStoreError> {
        Self::parse(&format!("meetings/{meeting_id}/export/{export_file}"))
    }

    /// `meetings/<meeting-id>/recovery/<quarantined-name>`
    pub fn meeting_recovery(
        meeting_id: &str,
        quarantined_name: &str,
    ) -> Result<Self, AssetStoreError> {
        Self::parse(&format!(
            "meetings/{meeting_id}/recovery/{quarantined_name}"
        ))
    }

    /// `assets/<asset-id>/original` or `assets/<asset-id>/original.<ext>`
    pub fn asset_blob(asset_id: &str, extension: Option<&str>) -> Result<Self, AssetStoreError> {
        match extension {
            Some(ext) => Self::parse(&format!("assets/{asset_id}/original.{ext}")),
            None => Self::parse(&format!("assets/{asset_id}/original")),
        }
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for StorageKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// One `[A-Za-z0-9._-]+` component that is neither `.` nor `..`.
fn is_key_component(component: &str) -> bool {
    component != "."
        && component != ".."
        && component
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'-'))
}

/// Lower-case hyphenated UUID shape (`[0-9a-f]{8}-…-{12}`), std-only.
fn is_lower_uuid(s: &str) -> bool {
    let bytes = s.as_bytes();
    if bytes.len() != 36 {
        return false;
    }
    for (i, &b) in bytes.iter().enumerate() {
        match i {
            8 | 13 | 18 | 23 => {
                if b != b'-' {
                    return false;
                }
            }
            _ => {
                if !matches!(b, b'0'..=b'9' | b'a'..=b'f') {
                    return false;
                }
            }
        }
    }
    true
}

fn require_uuid(id: &str) -> Result<(), AssetStoreError> {
    if is_lower_uuid(id) {
        Ok(())
    } else {
        Err(invalid(format!(
            "`{id}` is not a lower-case hyphenated UUID (user filenames can never escape their directory)"
        )))
    }
}

/// `chunk-file := seq "-" source (".wav" | ".wav.part")`, seq = 6*DIGIT.
fn parse_chunk_file(file: &str) -> Result<(), AssetStoreError> {
    let base = file
        .strip_suffix(".wav.part")
        .or_else(|| file.strip_suffix(".wav"))
        .ok_or_else(|| {
            invalid(format!(
                "chunk file {file:?} must end in `.wav` or `.wav.part`"
            ))
        })?;
    let (sequence, source) = base
        .split_once('-')
        .ok_or_else(|| invalid(format!("chunk file {file:?} lacks `<seq>-<source>`")))?;
    if sequence.len() != 6 || !sequence.bytes().all(|b| b.is_ascii_digit()) {
        return Err(invalid(format!(
            "chunk sequence {sequence:?} is not exactly 6 digits"
        )));
    }
    AudioSource::parse(source).map(|_| ()).ok_or_else(|| {
        invalid(format!(
            "chunk source {source:?} is not `microphone`|`system`"
        ))
    })
}

/// `export-file := export-name "." ("md" | "txt" | "json" | "wav")`.
/// `export-name` is always store-generated, never a user/import filename.
fn parse_export_file(file: &str) -> Result<(), AssetStoreError> {
    let (name, ext) = file
        .rsplit_once('.')
        .ok_or_else(|| invalid(format!("export file {file:?} lacks an extension")))?;
    if name.is_empty() || !is_key_component(name) {
        return Err(invalid(format!("invalid export name {name:?}")));
    }
    if !matches!(ext, "md" | "txt" | "json" | "wav") {
        return Err(invalid(format!(
            "export extension {ext:?} is not md|txt|json|wav"
        )));
    }
    Ok(())
}

/// `asset-file := "original" ("." ext)?`, ext = 1*8(ALPHA / DIGIT).
fn parse_asset_file(file: &str) -> Result<(), AssetStoreError> {
    match file.split_once('.') {
        None => {
            if file == "original" {
                Ok(())
            } else {
                Err(invalid(format!(
                    "asset file {file:?} must be `original` or `original.<ext>`"
                )))
            }
        }
        Some(("original", ext)) => {
            if (1..=8).contains(&ext.len()) && ext.bytes().all(|b| b.is_ascii_alphanumeric()) {
                Ok(())
            } else {
                Err(invalid(format!(
                    "asset extension {ext:?} is not 1-8 alphanumeric characters"
                )))
            }
        }
        Some((other, _)) => Err(invalid(format!(
            "asset file must be named `original`, got {other:?}"
        ))),
    }
}

fn invalid(detail: impl Into<String>) -> AssetStoreError {
    AssetStoreError::InvalidKey(detail.into())
}

